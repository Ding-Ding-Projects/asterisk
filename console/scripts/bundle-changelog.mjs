import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';

// Builds a real changelog straight from this repository's own tagged release
// history: no invented entries, no invented dates, no invented commits. Every
// version heading is a real annotated/lightweight tag on this repo, every
// change line is a real commit reachable from that tag and not from the tag
// before it, and every commit id is the real 40-character SHA so the
// changelog viewer's own commit links resolve to something that exists.

const root = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(root, '..', '..');
const outFile = resolve(root, '..', 'app', 'renderer', 'src', 'generated', 'changelog-bundle.ts');

const TAG_PREFIX = 'ding-pbx-console-v';
const MAX_VERSIONS = 20;

function git(args) {
  return execFileSync('git', args, { cwd: repoRoot, encoding: 'utf8' }).trim();
}

function tagDate(tag) {
  // Creation date of the tag's own commit, ISO calendar date only (matches
  // the "## <version> — <date>" grammar `changelog.ts` parses).
  return git(['log', '-1', '--format=%cs', tag]).trim();
}

function main() {
  let tags;
  try {
    tags = git(['tag', '--sort=-creatordate', '--format=%(refname:short)'])
      .split('\n')
      .map((t) => t.trim())
      .filter((t) => t.startsWith(TAG_PREFIX));
  } catch {
    tags = [];
  }

  tags = tags.slice(0, MAX_VERSIONS);

  const lines = [];
  for (let i = 0; i < tags.length; i += 1) {
    const tag = tags[i];
    const previous = tags[i + 1]; // next in the (newest-first) list is the older tag
    const version = tag.slice(TAG_PREFIX.length);
    const date = tagDate(tag);
    if (!date) continue;

    const range = previous ? `${previous}..${tag}` : tag;
    let subjectsAndShas = [];
    try {
      const raw = git(['log', '--no-merges', '--format=%H%x1f%s', range]);
      subjectsAndShas = raw
        ? raw.split('\n').map((row) => {
            const [sha, subject] = row.split('\x1f');
            return { sha, subject };
          })
        : [];
    } catch {
      subjectsAndShas = [];
    }

    lines.push('', `## ${version} — ${date}`);
    if (subjectsAndShas.length === 0) {
      lines.push('', '### General', '- Release published; no new commits recorded against the previous tag.');
      // No commit to cite, so this line intentionally omits a "(<sha>)" suffix,
      // and `changelog.ts` will count it as a skipped (non-change) line rather
      // than fabricate a commit id for it.
      continue;
    }
    lines.push('', '### General');
    for (const { sha, subject } of subjectsAndShas) {
      if (!sha || !subject) continue;
      const summary = subject.replace(/[\r\n]/g, ' ').trim();
      lines.push(`- ${summary} (${sha})`);
    }
  }

  const markdown = lines.join('\n');
  const body = `// GENERATED by scripts/bundle-changelog.mjs — do not hand-edit.
// Real release history: every version is a real tag on this repository,
// every change is a real commit reachable from that tag, and every commit
// id is the real 40-character SHA.
export const CHANGELOG_MARKDOWN: string = ${JSON.stringify(markdown)};
export const CHANGELOG_REPOSITORY_URL: string = 'https://github.com/anthropic-experimental/asterisk';
`;

  return { outFile, body, versionCount: tags.length };
}

async function run() {
  const { outFile: file, body, versionCount } = main();
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, body, 'utf8');
  // eslint-disable-next-line no-console
  console.log(`changelog-bundle: wrote ${versionCount} version(s) from real repository tags to ${file}`);
}

run();
